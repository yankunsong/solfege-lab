// Map a browser/URL language tag to one we support.
function matchLanguage(tag) {
  if (!tag) return null;
  const t = tag.toLowerCase();
  if (t.startsWith("zh")) {
    return /hant|tw|hk|mo/.test(t) ? "zh-Hant" : "zh-Hans";
  }
  const base = t.split("-")[0];
  return LANGUAGES.some((l) => l.code === base) ? base : null;
}
